// Все тексты бота собраны в одном месте — их легко поправить,
// не роясь по остальному коду. Тон везде нейтральный: без похвалы,
// без "молодец", без слов "дисциплина/норма/должен".

const REMINDER_QUESTIONS = [
  "Где ты сейчас?",
  "Кто наблюдает в этот момент?",
  "Какое тело у тебя сейчас — напряжённое или свободное?",
  "Что делает ум прямо сейчас, пока ты читаешь это?",
  "Какая эмоция фонит на фоне, пока ты занят делом?",
  "Остановись на секунду. Что ты только что делал механически?",
  "Если бы кто-то спросил «ты здесь?» — что бы ты ответил честно?",
  "Заметь дыхание. Оно твоё, или само по себе?",
  "Что в теле сейчас — плечи, челюсть, живот?",
  "Секунда без цели: просто заметь, что вокруг.",
  "Кто сейчас читает этот вопрос?",
  "Между этим сообщением и следующим действием — есть ли пауза?",
];

function randomReminderQuestion() {
  return REMINDER_QUESTIONS[Math.floor(Math.random() * REMINDER_QUESTIONS.length)];
}

